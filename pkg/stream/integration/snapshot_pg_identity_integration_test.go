// Test_SnapshotToPostgres_IdentitySequenceRestartedBeforeUse verifies that the
// snapshot restores an identity sequence that was repositioned on the source
// and not used since.
//
// After ALTER TABLE ... ALTER COLUMN ... RESTART WITH 500 the sequence holds
// last_value = 500 with is_called = false. pg_sequence_last_value returns NULL
// for such a sequence, so a query that falls back to the sequence start value
// restores the target at 1 instead of 500.
func Test_SnapshotToPostgres_IdentitySequenceRestartedBeforeUse(t *testing.T) {
	if os.Getenv("PGSTREAM_INTEGRATION_TESTS") == "" {
		t.Skip("skipping integration test...")
	}

	var snapshotPGURL string
	pgcleanup, err := testcontainers.SetupPostgresContainer(context.Background(), &snapshotPGURL, testcontainers.Postgres14, "config/postgresql.conf")
	require.NoError(t, err)
	defer pgcleanup()

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	testTable := fmt.Sprintf("snapshot_identity_restart_%d", time.Now().UnixNano())

	execQueryWithURL(t, ctx, snapshotPGURL, fmt.Sprintf(
		`CREATE TABLE %s(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text)`, testTable))
	execQueryWithURL(t, ctx, snapshotPGURL, fmt.Sprintf(
		`INSERT INTO %s(name) VALUES ('a'),('b')`, testTable))
	execQueryWithURL(t, ctx, snapshotPGURL, fmt.Sprintf(
		`ALTER TABLE %s ALTER COLUMN id RESTART WITH 500`, testTable))

	cfg := &stream.Config{
		Listener:  testPostgresListenerCfgWithSnapshot(snapshotPGURL, targetPGURL, []string{testTable}),
		Processor: testPostgresProcessorCfg(),
	}
	require.NoError(t, stream.Snapshot(ctx, testLogger(), cfg, nil))

	sourceConn, err := pglib.NewConn(ctx, snapshotPGURL)
	require.NoError(t, err)
	defer sourceConn.Close(ctx)

	targetConn, err := pglib.NewConn(ctx, targetPGURL)
	require.NoError(t, err)
	defer targetConn.Close(ctx)

	rows := getIDNameRows(t, ctx, targetConn, fmt.Sprintf("SELECT id, name FROM %s ORDER BY id", testTable))
	require.Equal(t, []idNameRow{{id: 1, name: "a"}, {id: 2, name: "b"}}, rows)

	sourceState, err := identitySequenceState(ctx, sourceConn, testTable)
	require.NoError(t, err)
	require.Equal(t, sequenceState{lastValue: 500, isCalled: false}, sourceState)

	targetState, err := identitySequenceState(ctx, targetConn, testTable)
	require.NoError(t, err)
	require.Equal(t, sourceState, targetState,
		"target identity sequence must keep the position the source was restarted at")
}
