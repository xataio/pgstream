package postgres

import (
	"context"
	"os"
	"testing"

	"github.com/stretchr/testify/require"
	pglib "github.com/xataio/pgstream/internal/postgres"
	"github.com/xataio/pgstream/internal/testcontainers"
)

// Test_SetSequenceQuery_OnlyMovesForward runs the setval queries against a real
// Postgres: rows reach the target in commit order, so the id of the last row
// can be below the ids already replicated, and the sequence must stay above them.
func Test_SetSequenceQuery_OnlyMovesForward(t *testing.T) {
	if os.Getenv("PGSTREAM_INTEGRATION_TESTS") == "" {
		t.Skip("skipping integration test...")
	}

	ctx := context.Background()

	var pgURL string
	cleanup, err := testcontainers.SetupPostgresContainer(ctx, &pgURL, testcontainers.Postgres17)
	require.NoError(t, err)
	defer cleanup()

	conn, err := pglib.NewConn(ctx, pgURL)
	require.NoError(t, err)
	defer conn.Close(ctx)

	tests := []struct {
		name  string
		setup []string
		seq   sequenceTarget
		// sequenceName is the pg_sequences name of the sequence the case moves
		sequenceName string
		schema       string
		table        string
		// values are applied in order, each as its own setval
		values []int64

		wantLastValue int64
	}{
		{
			name:          "first value on a sequence nothing was drawn from",
			setup:         []string{`CREATE TABLE fresh(id serial PRIMARY KEY)`},
			schema:        "public",
			sequenceName:  "fresh_id_seq",
			table:         "fresh",
			seq:           sequenceTarget{name: "fresh_id_seq"},
			values:        []int64{3},
			wantLastValue: 3,
		},
		{
			name:          "a lower id does not move the sequence back",
			setup:         []string{`CREATE TABLE ascending(id serial PRIMARY KEY)`},
			schema:        "public",
			sequenceName:  "ascending_id_seq",
			table:         "ascending",
			seq:           sequenceTarget{name: "ascending_id_seq"},
			values:        []int64{7, 6},
			wantLastValue: 7,
		},
		{
			name:          "a higher id moves the sequence forward",
			setup:         []string{`CREATE TABLE forward(id serial PRIMARY KEY)`},
			schema:        "public",
			sequenceName:  "forward_id_seq",
			table:         "forward",
			seq:           sequenceTarget{name: "forward_id_seq"},
			values:        []int64{7, 6, 9},
			wantLastValue: 9,
		},
		{
			name:          "the same id again",
			setup:         []string{`CREATE TABLE repeated(id serial PRIMARY KEY)`},
			schema:        "public",
			sequenceName:  "repeated_id_seq",
			table:         "repeated",
			seq:           sequenceTarget{name: "repeated_id_seq"},
			values:        []int64{4, 4},
			wantLastValue: 4,
		},
		{
			name:          "sequence resolved from the owning column",
			setup:         []string{`CREATE TABLE identity_col(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)`},
			schema:        "public",
			sequenceName:  "identity_col_id_seq",
			table:         "identity_col",
			seq:           sequenceTarget{column: "id"},
			values:        []int64{12, 5},
			wantLastValue: 12,
		},
		{
			name:          "schema qualified and quoted sequence",
			setup:         []string{`CREATE SCHEMA "Sales Data"`, `CREATE TABLE "Sales Data"."Order Items"(id serial PRIMARY KEY)`},
			schema:        "Sales Data",
			sequenceName:  "Order Items_id_seq",
			table:         "Order Items",
			seq:           sequenceTarget{name: `"Sales Data"."Order Items_id_seq"`},
			values:        []int64{20, 10},
			wantLastValue: 20,
		},
		{
			name: "descending sequence moves down",
			setup: []string{
				`CREATE SEQUENCE descending_seq INCREMENT -1 MINVALUE -1000 MAXVALUE -1 START -1`,
				`CREATE TABLE descending(id bigint PRIMARY KEY DEFAULT nextval('descending_seq'))`,
			},
			schema:        "public",
			sequenceName:  "descending_seq",
			table:         "descending",
			seq:           sequenceTarget{name: "descending_seq"},
			values:        []int64{-10, -5, -20},
			wantLastValue: -20,
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			for _, stmt := range tc.setup {
				_, err := conn.Exec(ctx, stmt)
				require.NoError(t, err)
			}

			for _, v := range tc.values {
				q := setSequenceQuery(tc.schema, tc.table, tc.seq, v)
				_, err := conn.Exec(ctx, q.sql, q.args...)
				require.NoError(t, err)
			}

			var last int64
			err := conn.QueryRow(ctx, []any{&last}, `SELECT last_value FROM pg_sequences WHERE schemaname = $1 AND sequencename = $2`,
				tc.schema, tc.sequenceName)
			require.NoError(t, err)
			require.Equal(t, tc.wantLastValue, last)
		})
	}
}
